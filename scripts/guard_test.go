func TestGuardFailsClosed(t *testing.T) {
	t.Parallel()
	project := setupProject(t, noRed)
	guard := scriptPath(t, "tdd-guard.sh")
	env := []string{"CLAUDE_PROJECT_DIR=" + project}

	t.Run("unparseable input", func(t *testing.T) {
		t.Parallel()
		r := run(t, project, env, "{not json", guard, "edit")
		if r.code != 2 || !strings.Contains(r.stderr, "parse") {
			t.Fatalf("exit = %d, stderr = %q; want 2 mentioning parse", r.code, r.stderr)
		}
	})
	t.Run("jq unavailable", func(t *testing.T) {
		t.Parallel()
		in := hookJSON(t, "Edit", map[string]any{"file_path": filepath.Join(project, "a_test.go")}, project)
		r := run(t, project, append(env, "TDD_GUARD_JQ=/nonexistent/jq"), in, guard, "edit")
		if r.code != 2 || !strings.Contains(r.stderr, "jq") {
			t.Fatalf("exit = %d, stderr = %q; want 2 mentioning jq", r.code, r.stderr)
		}
	})
	t.Run("unknown mode", func(t *testing.T) {
		t.Parallel()
		r := run(t, project, env, "{}", guard, "frobnicate")
		if r.code != 2 {
			t.Fatalf("exit = %d, want 2", r.code)
		}
	})
}

func TestGuardBashDecisions(t *testing.T) {
	t.Parallel()
	cases := []struct {
		command string
		want    int
	}{
		{"make red PKG=./internal/x/core RUN='^TestX$'", 0},
		{"make green", 0},
		{"go test ./...", 0},
		{"cat .tdd/red", 0},
		{"ls -la .tdd", 0},
		{"echo hi > .tdd/red", 2},
		{"touch .tdd/red", 2},
		{"mkdir -p .tdd && date > .tdd/red", 2},
		{"cat .tdd/red; touch .tdd/red", 2},
		{"cp /tmp/x .tdd/red", 2},
		{"rm -f .tdd/red", 2},
		{"make red PKG=./x RUN=TestX; touch .tdd/red", 2},
	}
	for _, tc := range cases {
		t.Run(tc.command, func(t *testing.T) {
			t.Parallel()
			r := guardBash(t, setupProject(t, noRed), tc.command)
			if r.code != tc.want {
				t.Fatalf("exit = %d, want %d; stderr: %s", r.code, tc.want, r.stderr)
			}
		})
	}
}
