package scripts_test

import (
	"path/filepath"
	"strings"
	"testing"
	"time"
)

const validRed = "recorded-by: make red\npkg: ./internal/x/core\nrun: ^TestX$\nkind: test\n"

type redState int

const (
	noRed redState = iota
	freshRed
	staleRed
	forgedRed
)

func setupProject(t *testing.T, state redState) string {
	t.Helper()
	dir := t.TempDir()
	switch state {
	case noRed:
	case freshRed:
		writeFile(t, dir, ".tdd/red", validRed)
	case staleRed:
		p := writeFile(t, dir, ".tdd/red", validRed)
		age(t, p, 31*time.Minute)
	case forgedRed:
		writeFile(t, dir, ".tdd/red", "i promise the test failed\n")
	}
	return dir
}

func guardEdit(t *testing.T, project, tool, path string, env ...string) result {
	t.Helper()
	in := hookJSON(t, tool, map[string]any{"file_path": path, "content": "package x\n"}, project)
	env = append([]string{"CLAUDE_PROJECT_DIR=" + project}, env...)
	return run(t, project, env, in, scriptPath(t, "tdd-guard.sh"), "edit")
}

func guardBash(t *testing.T, project, command string) result {
	t.Helper()
	in := hookJSON(t, "Bash", map[string]any{"command": command}, project)
	return run(t, project, []string{"CLAUDE_PROJECT_DIR=" + project}, in, scriptPath(t, "tdd-guard.sh"), "bash")
}

func TestGuardEditDecisions(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name  string
		path  string // relative to project unless absolute
		state redState
		want  int
	}{
		{"test file", "internal/x/core/a_test.go", noRed, 0},
		{"go file under testdata", "internal/x/testdata/fixture.go", noRed, 0},
		{"markdown doc", "docs/progress.md", noRed, 0},
		{"go file under docs", "docs/examples/example.go", noRed, 0},
		{"migration sql", "migrations/00001_init.sql", noRed, 0},
		{"go file under migrations", "migrations/embed.go", noRed, 0},
		{"compose config", "compose.yaml", noRed, 0},
		{"makefile", "Makefile", noRed, 0},
		{"go.mod", "go.mod", noRed, 0},
		{"shell script", "scripts/tdd-guard.sh", noRed, 0},
		{"sqlc output dir", "internal/x/adapters/postgres/sqlcgen/queries.sql.go", noRed, 0},
		{"_gen.go suffix", "internal/x/mock_gen.go", noRed, 0},
		{"outside project", "/somewhere/else/main.go", noRed, 0},

		{"production go without red", "internal/x/core/a.go", noRed, 2},
		{"production go with fresh red", "internal/x/core/a.go", freshRed, 0},
		{"production go with stale red", "internal/x/core/a.go", staleRed, 2},
		{"production go with forged red", "internal/x/core/a.go", forgedRed, 2},
		{"cmd main without red", "cmd/api/main.go", noRed, 2},
		{"dir merely prefixed docs", "internal/docsgen/a.go", noRed, 2},
		{"traversal out of test-looking dir", "internal/a_test.go/../a.go", noRed, 2},
		{"traversal back into project", "internal/x/../../internal/x/core/a.go", noRed, 2},
		{"traversal out of an allowed dir", "docs/../internal/x/core/a.go", noRed, 2},
		{"traversal out of testdata", "internal/x/testdata/../core/a.go", noRed, 2},

		{"guard state file is never writable", ".tdd/red", freshRed, 2},
		{"guard state dir is never writable", ".tdd/other", noRed, 2},
	}
	for _, tool := range []string{"Edit", "Write", "MultiEdit"} {
		for _, tc := range cases {
			t.Run(tool+"/"+tc.name, func(t *testing.T) {
				t.Parallel()
				project := setupProject(t, tc.state)
				path := tc.path
				if !filepath.IsAbs(path) {
					path = filepath.Join(project, path)
				}
				// Join cleans the path; keep the raw traversal form for those cases.
				if strings.Contains(tc.path, "..") {
					path = project + "/" + tc.path
				}
				r := guardEdit(t, project, tool, path)
				if r.code != tc.want {
					t.Fatalf("exit = %d, want %d\nstdout: %s\nstderr: %s", r.code, tc.want, r.stdout, r.stderr)
				}
				if tc.want == 2 && r.stderr == "" {
					t.Fatalf("blocked without an explanation on stderr")
				}
			})
		}
	}
}

func TestGuardRelativePathResolvesAgainstProject(t *testing.T) {
	t.Parallel()
	project := setupProject(t, noRed)
	r := guardEdit(t, project, "Write", "internal/x/core/a.go")
	if r.code != 2 {
		t.Fatalf("exit = %d, want 2; stderr: %s", r.code, r.stderr)
	}
}

func TestGuardBlockMessageExplainsHowToProceed(t *testing.T) {
	t.Parallel()
	project := setupProject(t, noRed)
	r := guardEdit(t, project, "Edit", filepath.Join(project, "internal/x/core/a.go"))
	if r.code != 2 {
		t.Fatalf("exit = %d, want 2", r.code)
	}
	for _, want := range []string{"internal/x/core/a.go", "make red", "CLAUDE.md"} {
		if !strings.Contains(r.stderr, want) {
			t.Errorf("stderr missing %q:\n%s", want, r.stderr)
		}
	}
}

func TestGuardAllowsExistingGeneratedFile(t *testing.T) {
	t.Parallel()
	project := setupProject(t, noRed)
	p := writeFile(t, project, "internal/x/adapters/postgres/db/models.go",
		"// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.31.1\n\npackage db\n")
	if r := guardEdit(t, project, "Edit", p); r.code != 0 {
		t.Fatalf("exit = %d, want 0; stderr: %s", r.code, r.stderr)
	}
}

func TestGuardDoesNotTrustGeneratedMarkerOutsideHeader(t *testing.T) {
	t.Parallel()
	project := setupProject(t, noRed)
	body := "package x\n\n" + strings.Repeat("// filler\n", 10) + "// Code generated by sqlc. DO NOT EDIT.\n"
	p := writeFile(t, project, "internal/x/core/a.go", body)
	if r := guardEdit(t, project, "Edit", p); r.code != 2 {
		t.Fatalf("exit = %d, want 2", r.code)
	}
}

func TestGuardFreshnessBoundary(t *testing.T) {
	t.Parallel()
	project := setupProject(t, freshRed)
	age(t, filepath.Join(project, ".tdd/red"), 29*time.Minute)
	if r := guardEdit(t, project, "Edit", filepath.Join(project, "a.go")); r.code != 0 {
		t.Fatalf("29-minute-old red: exit = %d, want 0; stderr: %s", r.code, r.stderr)
	}
}

